export async function lockGameTables(): Promise<number> {
  const anon = await pool.query("SELECT 1 FROM pg_roles WHERE rolname = 'anon'");
  if (!anon.rowCount) return 0;
  const found = await pool.query("SELECT tablename FROM pg_tables WHERE schemaname = 'public' AND tablename = ANY($1)", [GAME_TABLES]);
  for (const { tablename } of found.rows as { tablename: string }[]) {
    if (!/^[a-z_][a-z0-9_]*$/.test(tablename)) continue;
    await pool.query(`ALTER TABLE public.${tablename} ENABLE ROW LEVEL SECURITY`);
    await pool.query(`REVOKE ALL ON TABLE public.${tablename} FROM anon, authenticated`);
  }
  return found.rowCount ?? 0;
}
